"""Unit visual test bench: generate the most basic map with ONE unit under test, safely.

    python scripts/tools/unitbench.py --proto zpSPCLondonBasilica
    python scripts/tools/unitbench.py --proto zpSPCLondonBasilica --control House --dist 24 --owner 1
    python scripts/tools/unitbench.py --proto House --stem 000_unitbench_ctl      # control-only run
    python scripts/tools/unitbench.py --proto X --out C:/some/dir --json report.json --no-preflight
    python scripts/tools/unitbench.py --proto zzA,zzB,zzC,zzD --stem 000_bonebench     # variant grid, one map

What it writes: <stem>.xs + <stem>.xml into the Steam install's Game/RandMaps (the Scenario Editor
re-reads them on every File > New; never into the mod folder unless --out says so).

Several comma-separated --proto names = a VARIANT GRID: one generation shows every variant side by side
instead of one game restart per variant. Rows of --cols subjects, --spacing m apart, --rowgap m between
rows (44 m keeps a 26 m tall building from hiding the row behind it), centred on the map centre where the
editor camera opens; the rows run along (x - z), which is screen-horizontal there (+x runs up-right: bench
shot 2026-09-17). Subject 1 = front row, left; numbering runs left to right, front to back. The players
move to a 0.42 ring so their Town Centers stay out of the picture; the control stands in front, centred.

Why the bench crashed before (evidence in scripts/maps/000_hkt_test.xs, commit 7130e597, and the
map-minimap skill): (1) a stripped spine - missing rmSetMapSize / rmTerrainInitialize / player
placement dies at 0xC0000005 +0x7E9D2D; (2) missing includes + chooseMercs() - a Saloon's train list is
built from the mercenary set at world creation, generation aborted at +0xA7508D; (3) a proto whose
animfile / model / material / texture does not resolve, or an LF-only art XML (renders nothing).
This tool freezes the spine in a template that is never edited by hand, substitutes only the proto
names, self-checks the spine in its own output, and runs an offline pre-flight for (3) before the
game is touched. A vanilla control unit stands beside the subject so a crash is attributable.

Pre-flight (offline, no game needed):
  P1 proto exists      data/protomods.xml, else the live Data.bar protoy (never the repo snapshot)
  P2 animfile resolves mod art/ first, then the archives
  P3 model + material  every <file> in the animfile -> .gr2 and .material (mod or archives)
  P4 textures          material <texture override> and animfile <texture> -> .ddt (mod or archives)
  P5 art XML is CRLF   LF-only animfile/material = unit places, model never renders (hard rule)
  P6 mapcheck static   on the generated script; the stale-snapshot S4 for a proto verified in P1
                       is downgraded to a note
  P7 spine self-check  every mandatory spine line is present in the generated text

Exit 0 = written (pre-flight clean or --no-preflight), 1 = pre-flight FAIL (nothing written unless
--force), 2 = usage error. The JSON report (--json) is what rm-unit-bench and bench_run.py consume.
"""
